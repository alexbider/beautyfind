export const CONTENT_UPDATED = { iso: '2026-09-17', label: '17 בספטמבר 2026' };

export type Responsibility = 'medical' | 'professional';

export interface CategoryContent {
  /** Hero and row image in /public/assets. */
  img: string;
  /** One line under the name in lists (Treatments rows). */
  blurb: string;
  /** Search terms that should match this category on /treatments. */
  tags: string[];
  /** Short "top treatments" line for the Region page rows. */
  examples: string;
  /** Typical frequency, e.g. "כל 4–6 חודשים". */
  freq: string;
  /** Opening answer paragraph on the category page (no numbers). */
  answer: string;
  /** "מה התחום כולל" paragraphs. */
  paras: string[];
  /** Who may perform: the regulation box. */
  regTitle: string;
  regBody: string;
  /** Common treatments in the category. */
  subs: Array<{ name: string; body: string }>;
  /** What to ask before booking. */
  ask: string[];
  /** Possible side effects and risks, stated generally. */
  risks: string[];
  faqs: Array<{ q: string; a: string }>;
  /** Related category slugs (3). */
  related: string[];
}

