// Regenerates src/components/home/israel-land.ts. Run: node scripts/gen-israel-land.mjs
// Projection must match IsraelMap.tsx: Web Mercator, bounds 29.49..33.34N / 34.27..35.90E filling 54.8% of a 800x900 plane.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { feature } = require('topojson-client');
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-10m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);
const yM = lat => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 180 / 2));
const s = (0.548 * 900) / (yM(33.34) - yM(29.49));
const cy = (yM(33.34) + yM(29.49)) / 2, cx = ((34.27 + 35.9) / 2) * Math.PI / 180;
const P = ([lon, lat]) => [400 + ((lon * Math.PI) / 180 - cx) * s, 450 - (yM(lat) - cy) * s];
const geoms = land.features ? land.features.map(f => f.geometry) : [land.geometry];
const polys = geoms.flatMap(g => (g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates]));
// Clip each ring to the visible plane (with margin) and thin points closer than MIN units.
const B = { x0: -60, y0: -60, x1: 860, y1: 960 };
const MIN = 1.2;
function clip(pts) {
  const edges = [
    [p => p[0] >= B.x0, (a, b) => { const t = (B.x0 - a[0]) / (b[0] - a[0]); return [B.x0, a[1] + t * (b[1] - a[1])]; }],
    [p => p[0] <= B.x1, (a, b) => { const t = (B.x1 - a[0]) / (b[0] - a[0]); return [B.x1, a[1] + t * (b[1] - a[1])]; }],
    [p => p[1] >= B.y0, (a, b) => { const t = (B.y0 - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), B.y0]; }],
    [p => p[1] <= B.y1, (a, b) => { const t = (B.y1 - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), B.y1]; }],
  ];
  let out = pts;
  for (const [inside, cut] of edges) {
    const src = out; out = [];
    for (let i = 0; i < src.length; i++) {
      const a = src[(i + src.length - 1) % src.length], b = src[i];
      if (inside(b)) { if (!inside(a)) out.push(cut(a, b)); out.push(b); }
      else if (inside(a)) out.push(cut(a, b));
    }
    if (!out.length) break;
  }
  return out;
}
let d = '';
for (const poly of polys) for (const ring of poly) {
  const pts = clip(ring.map(P));
  if (pts.length < 3) continue;
  const kept = [pts[0]];
  for (const p of pts) { const q = kept[kept.length - 1]; if (Math.hypot(p[0] - q[0], p[1] - q[1]) >= MIN) kept.push(p); }
  if (kept.length < 3) continue;
  d += 'M' + kept.map(([x, y]) => `${Math.round(x * 10) / 10} ${Math.round(y * 10) / 10}`).join('L') + 'Z';
}
const header = `// Land outline around Israel from Natural Earth 1:10m land polygons (public domain), projected with the
// map's Web Mercator fit, clipped to the plane and thinned to 1.2 units. Coastlines only, no borders.
// Generated by scripts/gen-israel-land.mjs. Do not edit by hand.
`;
writeFileSync(new URL('../src/components/home/israel-land.ts', import.meta.url), `${header}export const LAND = '${d}';\n`);
console.log('israel-land.ts written,', d.length, 'chars');
